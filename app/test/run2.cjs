const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/*', r => { const u = r.request().url(); if (u.startsWith('https://i.ytimg.com') || u.startsWith('https://yt3')) return r.fulfill({ status: 200, contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180"><rect width="320" height="180" fill="#345"/></svg>' }); return r.abort(); });
  await p.setContent('<html><body></body></html>');
  await p.addScriptTag({ path: 'fix.js' }); await p.addScriptTag({ path: 'harness.out.js' });
  await p.waitForTimeout(800);
  const S = '/tmp/claude-0/-home-claude/75c71062-6ad6-5134-bd7b-3ff6222bc137/scratchpad/';
  const key = async (k, n = 1) => { for (let i = 0; i < n; i++) { await p.keyboard.press(k); await p.waitForTimeout(120); } };
  const shot = async (n) => { await p.waitForTimeout(400); await p.screenshot({ path: S + `ui_${n}.png` }); };
  const foc = () => p.evaluate(() => { const f = document.querySelector('.focused'); return f ? (f.className + ' | ' + (f.textContent || '').trim().replace(/\s+/g,' ').slice(0, 50)) : 'none'; });
  const press = async (a) => { await p.evaluate((a) => { const el = document.querySelector(`.player [data-a="${a}"]`); window.__f(el); }, a); await key('Enter'); await p.waitForTimeout(500); };
  await p.evaluate(() => { window.__f = (el) => { document.querySelectorAll('.focused').forEach(x => x.classList.remove('focused')); el.classList.add('focused'); }; });
  await key('Enter'); await p.waitForTimeout(700);
  await p.evaluate(() => { const v = app.player.video; Object.defineProperty(v, 'duration', { value: 180, configurable: true }); app.player.drawChapters(); app.player.drawProgress(); });
  await shot('11osd'); console.log('player', await foc());
  await key('ArrowRight', 20); console.log('rightmost', await foc());
  await press('quality'); await shot('18quality'); await key('Escape'); await press('audio'); await shot('19audio'); await key('Escape');
  await press('comments'); console.log('comments', await foc()); await key('ArrowDown', 3); await shot('12comments');
  await key('Escape'); console.log('after esc', await foc());
  await press('info'); await shot('13info'); console.log('info', await foc());
  await key('Escape'); await key('ArrowUp'); console.log('up from buttons', await foc()); await key('ArrowRight'); await shot('14seek');
  await press('like'); console.log('like (logged out)', await p.evaluate(() => document.getElementById('toast')?.textContent));
  await key('Escape'); await key('Escape'); await key('Escape'); console.log('closed', await foc());
  await p.evaluate(() => app.go('news')); await p.waitForTimeout(500); await shot('15news'); console.log('news', await foc());
  await p.evaluate(() => app.openPlaylist({ id: 'PLx', title: 'قائمة تجريبية' })); await p.waitForTimeout(500); await shot('16playlist'); console.log('pl', await foc());
  await p.evaluate(() => app.go('search')); await p.waitForTimeout(300); await shot('17search');
  console.log('ERRORS', errs);
  await b.close();
})();
